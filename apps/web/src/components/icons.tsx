type IconProps = {
  name: TagIconName;
  size: IconSize;
  className?: string;
};

/** One status icon, decorative (aria-hidden), in the text colour, with a 1.5 px stroke at any size. */
export function Icon({ name, size, className }: IconProps) {
  const svg: SVGProps<SVGSVGElement> = {
    className,
    viewBox: "0 0 24 24",
    width: size,
    height: size,
    fill: "none",
    stroke: "currentColor",
    strokeWidth: (1.5 * 24) / size,
    strokeLinecap: "round",
    strokeLinejoin: "round",
    "aria-hidden": true,
    focusable: false,
  };
  return (
    <svg {...svg} data-icon={name}>
      {ICON_SHAPES[name].map(([tag, attributes], index) => createElement(tag, { key: index, ...attributes }))}
    </svg>
  );
}
