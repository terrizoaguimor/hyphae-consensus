"""Regenerate the Rust tables of THIRD_PARTY_NOTICES.md.

Reads `cargo metadata` (read-only) for the workspace and writes one table
per target triple: crate, version, declared license expression, repository.
Crates with no `license` field are listed under "needs review" instead of
being guessed.

The script rewrites the whole file. It copies one block from the existing
THIRD_PARTY_NOTICES.md verbatim, markers included: everything between
`<!-- hand-written:start -->` and `<!-- hand-written:end -->`, that is the
web dependency table (generated separately with
`pnpm licenses list --prod --json` inside the toolchain container) and the
Fonts section. The title, the introduction, the Rust heading and the Hyphae
section come from the built-in text below, which is kept identical to the
committed file; edit both together.

If the existing file or either marker is missing, the script stops without
writing anything, so a run can never replace the hand-written sections with
stale text.

Usage (from the repository root, with cargo on PATH):
    python -I scripts/third_party_notices.py
"""

import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.md"
TARGETS = ["x86_64-unknown-linux-gnu", "x86_64-pc-windows-msvc"]
WORKSPACE_PREFIX = "path+file://"

START = "<!-- rust-dependencies:start -->"
END = "<!-- rust-dependencies:end -->"
KEEP_START = "<!-- hand-written:start -->"
KEEP_END = "<!-- hand-written:end -->"

HEADER = """\
# Third-party notices

Hyphae Consensus is licensed under the Apache License 2.0 (see LICENSE and NOTICE). \
It depends on the third-party components below, each under its own license. \
The Rust tables are generated by `scripts/third_party_notices.py` from `cargo metadata`; \
the web table is generated with `pnpm licenses list --prod --json`; the sections after it \
are written by hand. The script rewrites the whole file: it regenerates the Rust tables, \
writes this introduction, the headings and the Hyphae section from its built-in text, and \
copies only the web table and the Fonts section (between the `hand-written` markers) from \
the existing file verbatim, so edit anything outside the markers in the script as well.

## Rust dependencies

"""

HYPHAE = """\
## Hyphae

Hyphae Core and Hyphae Agent Memory (Celiums Solutions LLC, Apache-2.0) are
consumed through their public interfaces only. No Hyphae source is included
in this repository. A deployment that ships the Hyphae binary must ship
Hyphae's LICENSE, NOTICE and third-party notices alongside it.
"""


def kept_block():
    """Return the hand-written block of the existing file, markers included."""
    if not OUT.exists():
        raise SystemExit(f"{OUT.name} not found: nothing to keep the hand-written sections from")
    text = OUT.read_text(encoding="utf-8")  # universal newlines: CRLF checkouts read as LF
    if text.count(KEEP_START) != 1 or text.count(KEEP_END) != 1:
        raise SystemExit(f"{OUT.name}: expected exactly one {KEEP_START} and one {KEEP_END}")
    begin = text.index(KEEP_START)
    end = text.index(KEEP_END) + len(KEEP_END)
    if end <= begin:
        raise SystemExit(f"{OUT.name}: {KEEP_END} comes before {KEEP_START}")
    return text[begin:end]


def metadata(target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
        cwd=ROOT, capture_output=True, text=True, check=True,
    ).stdout
    return json.loads(out)


def rows(meta):
    members = set(meta["workspace_members"])
    resolved = {n["id"] for n in meta["resolve"]["nodes"]}
    result, review = [], []
    for pkg in meta["packages"]:
        if pkg["id"] in members or pkg["id"] not in resolved:
            continue
        if pkg["source"] and pkg["source"].startswith(WORKSPACE_PREFIX):
            continue
        entry = (pkg["name"], pkg["version"], pkg.get("license") or "", pkg.get("repository") or "")
        (result if entry[2] else review).append(entry)
    return sorted(set(result)), sorted(set(review))


def table(entries):
    lines = ["| Crate | Version | License | Repository |", "|---|---|---|---|"]
    for name, version, license_, repo in entries:
        lines.append(f"| {name} | {version} | {license_} | {repo} |")
    return "\n".join(lines)


def main():
    kept = kept_block()
    sections = []
    all_licenses = set()
    for target in TARGETS:
        meta = metadata(target)
        entries, review = rows(meta)
        for e in entries:
            for part in re.split(r"\s+(?:OR|AND|WITH)\s+|/", e[2]):
                all_licenses.add(part.strip("() "))
        sections.append(f"### Target `{target}` ({len(entries)} crates)\n\n{table(entries)}")
        if review:
            sections.append("#### Needs review (no license field)\n\n" + table(review))
    body = (
        HEADER
        + f"License expressions seen: {', '.join(sorted(all_licenses))}.\n\n"
        + f"{START}\n" + "\n\n".join(sections) + f"\n{END}\n\n"
        + kept + "\n\n"
        + HYPHAE
    )
    OUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}; licenses: {', '.join(sorted(all_licenses))}")


if __name__ == "__main__":
    sys.exit(main())
